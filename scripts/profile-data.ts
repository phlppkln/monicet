// Profiles the raw archive and writes docs/data-profile.md — a factual,
// regenerable overview of coverage and gaps (where data is missing, and
// how sampling effort changed over time).
//
//   pnpm data:profile

import { writeFileSync } from "node:fs";
import path from "node:path";

import { PROJECT_ROOT, readTable, type Row } from "./lib/dwca.ts";

const OUT = path.join(PROJECT_ROOT, "docs/data-profile.md");
const MONTHS = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split(" ");

// Cruise rows carry the home-harbour position, so longitude separates the
// island groups cleanly (Faial and Pico harbours are too close to split).
function islandGroup(lon: number) {
	if (lon > -26.5) return "São Miguel";
	if (lon > -27.6) return "Terceira";
	return "Faial/Pico";
}
const ISLANDS = ["São Miguel", "Terceira", "Faial/Pico"];

const count = <K>(map: Map<K, number>, key: K, by = 1) =>
	map.set(key, (map.get(key) ?? 0) + by);
const pct = (n: number, d: number) =>
	d ? `${((n / d) * 100).toFixed(1)}%` : "n/a";
const table = (header: string[], rows: (string | number)[][]) =>
	[
		`| ${header.join(" | ")} |`,
		`| ${header.map(() => "---").join(" | ")} |`,
		...rows.map((r) => `| ${r.join(" | ")} |`),
	].join("\n");

function main() {
	const events = readTable("event");
	const occurrences = readTable("occurrence");
	const emof = readTable("emof");

	const cruises = events.filter((e) => e.type === "cruise");
	const samples = events.filter((e) => e.type === "sample");
	const year = (e: Row) => Number(e.eventDate.slice(0, 4));
	const month = (e: Row) => Number(e.eventDate.slice(5, 7));
	const years = [...new Set(cruises.map(year))].sort((a, b) => a - b);

	// ── Effort: cruises per year × month, per island ──────────────────────
	const cruiseYM = new Map<string, number>();
	const cruiseIsland = new Map<string, number>();
	const islandOfCruise = new Map<string, string>();
	for (const c of cruises) {
		count(cruiseYM, `${year(c)}-${month(c)}`);
		const island = islandGroup(Number(c.decimalLongitude));
		islandOfCruise.set(c.eventID, island);
		count(cruiseIsland, `${year(c)}|${island}`);
	}
	let emptyMonths = 0;
	const ymRows = years.map((y) => {
		const cells = MONTHS.map((_, m) => {
			const v = cruiseYM.get(`${y}-${m + 1}`) ?? 0;
			if (!v) emptyMonths += 1;
			return v ? String(v) : "**0**";
		});
		return [String(y), ...cells];
	});

	// ── Sightings per year and per cruise ─────────────────────────────────
	const samplesByYear = new Map<number, number>();
	const parentsWithSighting = new Set<string>();
	for (const s of samples) {
		count(samplesByYear, year(s));
		parentsWithSighting.add(s.parentEventID);
	}
	const cruisesByYear = new Map<number, number>();
	for (const c of cruises) count(cruisesByYear, year(c));

	// ── Contributors (recordedBy) per year ────────────────────────────────
	const sampleById = new Map(samples.map((s) => [s.eventID, s]));
	const companiesByYear = new Map<number, Set<string>>();
	for (const o of occurrences) {
		const s = sampleById.get(o.eventID);
		if (!s) continue;
		const set = companiesByYear.get(year(s)) ?? new Set<string>();
		set.add(o.recordedBy);
		companiesByYear.set(year(s), set);
	}
	const companies = [...new Set(occurrences.map((o) => o.recordedBy))].sort();

	// ── Taxonomic resolution ──────────────────────────────────────────────
	const taxa = new Map<string, number>();
	for (const o of occurrences) count(taxa, o.scientificName);
	const nonSpecies = [...taxa].filter(([name]) => !name.includes(" "));

	// ── Measurement completeness (eMoF) ───────────────────────────────────
	// Every eMoF row hangs off an occurrenceID, but event-level facts
	// (Beaufort, visibility, instrument) are attached to only one occurrence
	// per sighting — so report coverage both ways. eMoF `id` is the eventID.
	const occByType = new Map<string, Set<string>>();
	const eventByType = new Map<string, Set<string>>();
	const values = new Map<string, Map<string, number>>();
	const addTo = (map: Map<string, Set<string>>, key: string, id: string) => {
		const set = map.get(key) ?? new Set<string>();
		set.add(id);
		map.set(key, set);
	};
	for (const m of emof) {
		addTo(occByType, m.measurementType, m.occurrenceID);
		addTo(eventByType, m.measurementType, m.id);
		const v = values.get(m.measurementType) ?? new Map<string, number>();
		count(v, m.measurementValue || "(empty)");
		values.set(m.measurementType, v);
	}
	const completeness = [...occByType.keys()].sort().map((type) => {
		const occ = occByType.get(type)?.size ?? 0;
		const ev = eventByType.get(type)?.size ?? 0;
		return [type, pct(occ, occurrences.length), pct(ev, samples.length)];
	});

	// ── Location sanity ───────────────────────────────────────────────────
	const pointOnly = samples.filter((s) =>
		s.footprintWKT.startsWith("POINT")
	).length;

	const md = `# Data profile

> Generated by \`pnpm data:profile\` from \`data/raw/\` — do not edit by hand.
> Interpretation and gap-filling ideas: [missing-data.md](missing-data.md).

## Table sizes

${table(
	["Table", "Rows"],
	[
		["event (cruises)", cruises.length.toLocaleString()],
		["event (sightings)", samples.length.toLocaleString()],
		["occurrence", occurrences.length.toLocaleString()],
		["extendedmeasurementorfact", emof.length.toLocaleString()],
	]
)}

- Cruises with **no** sighting at all: **${cruises.filter((c) => !parentsWithSighting.has(c.eventID)).length}** of ${cruises.length.toLocaleString()} (${pct(cruises.filter((c) => !parentsWithSighting.has(c.eventID)).length, cruises.length)}). Either trips without sightings are rare or they were rarely entered — the archive cannot tell which, so true absences (\"we looked, nothing was there\") are essentially unavailable.
- Sightings with a single point (boat did not stop / only one fix): ${pointOnly.toLocaleString()} (${pct(pointOnly, samples.length)}); the rest have an arrival–departure line.

## Effort proxy: cruises per year × month

Cruises (whale-watching trips) are the only effort information in the archive — there are no boat tracks or search hours. **Bold 0** = no recorded trip that month (${emptyMonths} of ${years.length * 12} year-months).

${table(["Year", ...MONTHS], ymRows)}

## Cruises per island group

Island group is inferred from the cruise's home-harbour longitude.

${table(
	["Year", ...ISLANDS, "Total"],
	years.map((y) => [
		y,
		...ISLANDS.map((i) => cruiseIsland.get(`${y}|${i}`) ?? 0),
		cruisesByYear.get(y) ?? 0,
	])
)}

## Sightings per cruise

${table(
	["Year", "Cruises", "Sighting events", "Sightings / cruise"],
	years.map((y) => {
		const c = cruisesByYear.get(y) ?? 0;
		const s = samplesByYear.get(y) ?? 0;
		return [y, c, s, c ? (s / c).toFixed(2) : "n/a"];
	})
)}

## Contributing companies (\`recordedBy\`) per year

${table(
	["Year", "#", "Companies"],
	years.map((y) => {
		const set = [...(companiesByYear.get(y) ?? [])].sort();
		return [y, set.length, set.join(", ")];
	})
)}

All contributors: ${companies.join(", ")}.

## Taxonomic resolution

${table(
	["Taxon", "Occurrence rows"],
	[...taxa]
		.sort((a, b) => b[1] - a[1])
		.map(([name, n]) => [
			nonSpecies.some(([ns]) => ns === name)
				? `**${name}** (family only)`
				: `*${name}*`,
			n.toLocaleString(),
		])
)}

## Measurement completeness

Share of occurrence rows, and of sighting events, that carry each measurement. Sea state, visibility and instrument describe the whole sighting, so the per-event column is the meaningful one for them; count, behaviour and life stage describe a species group, so read the per-occurrence column.

${table(["Measurement", "% of occurrences", "% of sighting events"], completeness)}

### Value distributions

${[...values]
	.map(([type, v]) => {
		const sorted = [...v].sort((a, b) => b[1] - a[1]);
		const shown = sorted
			.slice(0, 12)
			.map(([val, n]) => `\`${val}\` ${n.toLocaleString()}`)
			.join(" · ");
		const more =
			sorted.length > 12 ? ` · … (${sorted.length} distinct)` : "";
		return `- **${type}**: ${shown}${more}`;
	})
	.join("\n")}
`;

	writeFileSync(OUT, md, "utf8");
	console.log(`Wrote ${path.relative(PROJECT_ROOT, OUT)}`);
}

main();
